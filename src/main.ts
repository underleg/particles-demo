import { Application, Graphics, UPDATE_PRIORITY, WebGLRenderer } from 'pixi.js';
import type { Effect, ParticleDoc } from '@particlr/runtime';
import { loadParticleDoc } from './loadParticleDoc';
import { bandPoint, effectCentre } from './layout';
import { bindSelect } from './bindSelect';
import { countDrawCalls } from './drawCalls';
import { formatPerf, PerfWindow } from './perf';
import { createSpine, loadSpineAssets } from './spineAnimation';
import { SKULL, SPINE_URLS } from './skullArt';
import { BIRD_SIZE, FLOOR_Y, setBirdsExit, setSwirlAttractors, SETUPS, withCount, type Setup } from './skullLayer';
import { byAge, bySpeedX } from './drawOrder';
import { SkullSetup, type SkullMode } from './SkullSetup';
import { FloorSpin } from './floorSpin';
import { EmitterSway } from './EmitterSway';

const SKULL_MODES = ['flipbook', 'spine'] as const;
const INFO = ['hidden', 'shown'] as const;
// Particlr's validator caps a layer at 10,000 particles, and each setup is one layer.
const COUNTS = ['10', '100', '1000', '10000'] as const;
type Emitter = Setup;

// A live Spine skeleton per particle costs ~2 ms per 250 on this machine, so 10,000 would run at a few fps. Above
// this the Spine option is disabled and the flipbook is used.
const SPINE_MAX_COUNT = 1000;
// The setups' effects, each with the skull flipbook sheet embedded; generated by export.html.
const effectUrl = (setup: Setup) => `${import.meta.env.BASE_URL}effects/${setup}.prt`;
const SKULL_LAYER = 'pull';
// Particlr bounces skull centres off FLOOR_Y, so the floor is drawn below that by roughly half a landed skull. Skulls
// grow over life and so are near full size when they land; 18 px was measured by eye in the browser. Tilted skulls
// reach further in some directions, so a few still overlap the line.
const FLOOR_DRAW_OFFSET = 18;
// The fountain rises ~170 px above the emitter but lands only ~100 px below it, so lower the emitter to centre the
// whole picture in the open band rather than the emitter itself.
const EMITTER_DROP = 35;
// Birds spawn and are removed this far beyond the screen edges, so they enter and leave wholly off screen.
const BIRD_OFFSCREEN = BIRD_SIZE / 2 + 5;
// The slowest bird (40 px/s) takes ~20 s to cross a wide screen; simulate that far ahead so the flock opens spread
// right across, not bunched at the left edge.
const BIRD_WARM_UP_SECONDS = 40;
// Swirl's emitter sits lower than the cascade's: this far down the open band (the attractors are at half way).
const SWIRL_EMITTER_Y = 0.85;
// Swirl's emitter swings this fraction of the window width either side of centre (so from under one attractor to
// under the other), once every SWIRL_SWAY_PERIOD seconds.
const SWIRL_SWAY = 0.25;
const SWIRL_SWAY_PERIOD = 2;

function requireElement<T extends HTMLElement>(id: string, type: new () => T): T {
  const element = document.getElementById(id);
  if (!(element instanceof type)) throw new Error(`Missing #${id} (${type.name}) in index.html`);
  return element;
}

// Show a fatal error on the page too: otherwise a failure is just an empty dark screen.
function showFatal(error: unknown): void {
  console.error(error);
  const message = document.createElement('pre');
  message.id = 'error';
  message.textContent = error instanceof Error ? error.message : String(error);
  document.body.appendChild(message);
}

// Frame time is the CPU work of one frame (simulate + sync + Pixi's render submit), not the gap between frames:
// the first callback runs before everything else on the ticker, the last after Pixi's render (UPDATE_PRIORITY.LOW).
// `current` is read every frame because the menu can switch, or rebuild, the running effect.
function startPerfReadout(app: Application, current: () => Effect | null, line: HTMLElement): void {
  // Draw calls can only be counted on WebGL; WebGL is requested, but Pixi may still fall back.
  const takeDrawCalls = app.renderer instanceof WebGLRenderer ? countDrawCalls(app.renderer.gl) : null;
  const perfWindow = new PerfWindow(performance.now());
  let frameStart = 0;
  let maxParticles = 0;
  let measured: Effect | null = null;

  app.ticker.add(() => (frameStart = performance.now()), undefined, UPDATE_PRIORITY.INTERACTION);
  app.ticker.add(
    () => {
      const fx = current();
      if (!fx) return; // a setup is being built; the line shows that instead
      // The peak is per effect: carrying one setup's peak over to another would misreport it.
      if (fx !== measured) [measured, maxParticles] = [fx, 0];
      const now = performance.now();
      perfWindow.addFrame(now - frameStart, takeDrawCalls?.() ?? 0);
      maxParticles = Math.max(maxParticles, fx.particleCount);

      const averages = perfWindow.flush(now);
      if (!averages) return;
      line.textContent = formatPerf({
        ...averages,
        drawCalls: takeDrawCalls ? averages.drawCalls : null,
        emitters: fx.layers.filter((sim) => sim.layer.enabled).length,
        particles: fx.particleCount,
        maxParticles,
      });
    },
    undefined,
    UPDATE_PRIORITY.UTILITY,
  );
}

async function main(): Promise<void> {
  const top = requireElement('top', HTMLElement);
  const info = requireElement('info', HTMLElement);
  const perfLine = requireElement('perf', HTMLElement);
  const emitterSelect = requireElement('select-emitter', HTMLSelectElement);
  const skullSelect = requireElement('select-skulls', HTMLSelectElement);
  const countSelect = requireElement('select-count', HTMLSelectElement);
  const infoSelect = requireElement('select-info', HTMLSelectElement);
  const spineOption = [...skullSelect.options].find((o) => o.value === 'spine');
  if (!spineOption) throw new Error('#select-skulls has no Spine option');

  const app = new Application();
  await app.init({ resizeTo: window, background: '#0b0b14', antialias: true, preference: 'webgl' });
  document.body.appendChild(app.canvas);

  // The Spine art is only for Spine mode now; the flipbook sheet comes embedded in each effect file.
  await loadSpineAssets(SPINE_URLS);
  const newSkull = () => createSpine(SPINE_URLS, SKULL);
  const loaded = await Promise.all(SETUPS.map((setup) => loadParticleDoc(effectUrl(setup))));
  const effects = Object.fromEntries(SETUPS.map((setup, i) => [setup, loaded[i]])) as Record<Setup, ParticleDoc>;

  const floor = new Graphics();
  app.stage.addChild(floor); // first, so skulls draw over it

  const state = { emitter: 'cascade' as Emitter, mode: 'flipbook' as SkullMode, count: 100 };
  // Setups built for the current count, made on first show. A count change destroys them: a Particlr pool's capacity
  // is fixed when its effect is built, so a new count needs a new effect.
  const built = new Map<Emitter, SkullSetup>();
  let active: SkullSetup | null = null;
  // The swirl's current sway: replaced on each swirl build, its amplitude set by layout from the window width.
  let swirlSway = new EmitterSway(SWIRL_SWAY_PERIOD);

  // A point at fractions of the open band. offsetHeight is 0 while the footer is hidden, so effects take that space.
  const band = (fx: number, fy: number) =>
    bandPoint(app.screen.width, app.screen.height, top.offsetHeight, info.offsetHeight, fx, fy);
  const placeFor: Record<Emitter, (setup: SkullSetup) => void> = {
    cascade: (setup) => {
      const centre = band(0.5, 0.5);
      setup.view.container.position.set(centre.x, centre.y + EMITTER_DROP);
    },
    birds: (setup) => {
      // The birds' local origin is their spawn line, just off the left edge; the exit is just off the right edge.
      setup.view.container.position.set(-BIRD_OFFSCREEN, band(0.5, 0.5).y);
      setBirdsExit(setup.sim.layer, app.screen.width + 2 * BIRD_OFFSCREEN);
    },
    swirl: (setup) => {
      // The container sits at the emitter's centre position; the sway moves the emitter either side of it in x only.
      const emitter = band(0.5, SWIRL_EMITTER_Y);
      setup.view.container.position.set(emitter.x, emitter.y);
      swirlSway.amplitude = app.screen.width * SWIRL_SWAY;
      // Attractor positions are in the effect's frame, whose origin is the emitter's centre position.
      const local = (p: { x: number; y: number }) => ({ x: p.x - emitter.x, y: p.y - emitter.y });
      setSwirlAttractors(setup.fx, setup.sim.layer, local(band(0.25, 0.5)), local(band(0.75, 0.5)));
    },
  };
  const place = (emitter: Emitter, setup: SkullSetup) => placeFor[emitter](setup);
  const layout = () => {
    built.forEach((setup, emitter) => place(emitter, setup));
    const centre = effectCentre(app.screen.width, app.screen.height, top.offsetHeight, info.offsetHeight);
    floor
      .clear()
      .rect(0, centre.y + EMITTER_DROP + FLOOR_Y + FLOOR_DRAW_OFFSET, app.screen.width, 2)
      .fill({ color: 0x6a5acd });
  };

  const build = async (emitter: Emitter): Promise<SkullSetup> => {
    const recipes: Record<Emitter, () => Promise<SkullSetup>> = {
      cascade: () => {
        const doc = withCount(effects.cascade, 'cascade', state.count);
        // Skulls take a new random spin each time they hit the floor; seeded from the effect for repeatable runs.
        const floorSpin = new FloorSpin(FLOOR_Y, doc.seed);
        return SkullSetup.create(doc, SKULL_LAYER, byAge, newSkull, (_fx, sim) => floorSpin.apply(sim));
      },
      birds: () => SkullSetup.create(withCount(effects.birds, 'birds', state.count), SKULL_LAYER, bySpeedX, newSkull),
      swirl: () => {
        // A fresh sway per build, so a rebuilt emitter starts at the centre rather than jumping to mid-swing.
        const sway = new EmitterSway(SWIRL_SWAY_PERIOD);
        swirlSway = sway;
        const doc = withCount(effects.swirl, 'swirl', state.count);
        return SkullSetup.create(doc, SKULL_LAYER, byAge, newSkull, (fx, _sim, seconds) => sway.advance(fx, seconds));
      },
    };
    const setup = await recipes[emitter]();
    app.stage.addChild(setup.view.container);
    place(emitter, setup);
    if (emitter === 'birds') setup.warmUp(BIRD_WARM_UP_SECONDS); // after place, so it flies to this screen's exit
    return setup;
  };

  const show = async () => {
    let setup = built.get(state.emitter);
    if (!setup) {
      perfLine.textContent = `Building ${state.count.toLocaleString('en-US')} particles…`;
      // Let the browser paint the message before the build blocks the main thread.
      await new Promise((resolve) => requestAnimationFrame(resolve));
      setup = await build(state.emitter);
      built.set(state.emitter, setup);
    }
    built.forEach((s, emitter) => {
      s.view.container.visible = emitter === state.emitter;
      s.setSkullMode(state.mode);
    });
    floor.visible = state.emitter === 'cascade';
    active = setup;
  };
  // Menu changes run one at a time, so a change made while a setup is still building waits its turn: otherwise a
  // build started at the old count could finish after a count change and be kept.
  let queue = Promise.resolve();
  const enqueue = (task: () => void | Promise<void>) => {
    queue = queue.then(task).catch(showFatal);
  };
  const refresh = () => enqueue(show);

  bindSelect(infoSelect, INFO, (value) => {
    info.hidden = value === 'hidden';
    layout();
  });
  bindSelect(countSelect, COUNTS, (value) => {
    const count = Number(value);
    spineOption.disabled = count > SPINE_MAX_COUNT;
    if (spineOption.disabled && skullSelect.value === 'spine') {
      skullSelect.value = 'flipbook';
      state.mode = 'flipbook';
    }
    enqueue(() => {
      state.count = count;
      active = null;
      built.forEach((setup) => setup.destroy());
      built.clear();
    });
    refresh();
  });
  bindSelect(emitterSelect, SETUPS, (value) => {
    state.emitter = value;
    refresh();
  });
  bindSelect(skullSelect, SKULL_MODES, (value) => {
    state.mode = value;
    refresh();
  });
  app.renderer.on('resize', layout);

  // Only the shown setup is simulated; the other pauses and resumes where it was.
  app.ticker.add((t) => active?.step(t.deltaMS / 1000));
  startPerfReadout(app, () => active?.fx ?? null, perfLine);
}

main().catch(showFatal);
